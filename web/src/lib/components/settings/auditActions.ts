/** The label of an event, or the event itself when it has none. */
export function auditActionLabel(action: string): string {
	return AUDIT_ACTION_LABEL[action]?.() ?? action;
}

/** Failed attempts are drawn in the warning tone. */
export function auditActionFailed(action: string): boolean {
	return action.endsWith('.failed');
}

/** Every known event, to fill the filter. */
export function knownAuditActions(): string[] {
	return Object.keys(AUDIT_ACTION_LABEL);
}
